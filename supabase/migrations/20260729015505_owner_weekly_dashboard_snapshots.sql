CREATE TABLE IF NOT EXISTS public.ingredient_price_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raw_ingredient_id INTEGER NOT NULL
    REFERENCES public.raw_ingredients(id) ON DELETE CASCADE,
  previous_price DOUBLE PRECISION NOT NULL,
  new_price DOUBLE PRECISION NOT NULL,
  previous_net_weight DOUBLE PRECISION NOT NULL,
  new_net_weight DOUBLE PRECISION NOT NULL,
  previous_unit_cost DOUBLE PRECISION NOT NULL,
  new_unit_cost DOUBLE PRECISION NOT NULL,
  changed_by_user_id INTEGER
    REFERENCES public.users(id) ON DELETE SET NULL,
  source VARCHAR(50) NOT NULL DEFAULT 'inventory_edit',
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_ingredient_price_history_ingredient_changed
  ON public.ingredient_price_history(raw_ingredient_id, changed_at DESC);

CREATE INDEX IF NOT EXISTS ix_ingredient_price_history_changed_by
  ON public.ingredient_price_history(changed_by_user_id);

ALTER TABLE public.ingredient_price_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.ingredient_price_history FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.ingredient_price_history_id_seq FROM anon, authenticated;
