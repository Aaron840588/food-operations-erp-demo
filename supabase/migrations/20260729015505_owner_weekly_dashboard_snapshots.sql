UPDATE public.consignment_items AS item
SET
  food_cost_snapshot = COALESCE(item.food_cost_snapshot, item.cost_per_unit_snapshot, 0),
  labor_cost_snapshot = COALESCE(item.labor_cost_snapshot, product.labor_cost, 0),
  utility_cost_snapshot = COALESCE(item.utility_cost_snapshot, product.utility_cost, 0),
  total_cost_snapshot = COALESCE(
    item.total_cost_snapshot,
    COALESCE(item.cost_per_unit_snapshot, 0)
      + COALESCE(product.labor_cost, 0)
      + COALESCE(product.utility_cost, 0)
  ),
  cost_status_snapshot = COALESCE(item.cost_status_snapshot, 'legacy_estimate'),
  cost_snapshot_recorded_at = COALESCE(item.cost_snapshot_recorded_at, NOW())
FROM public.product_skus AS product
WHERE product.sku = item.sku
  AND (
    item.food_cost_snapshot IS NULL
    OR item.labor_cost_snapshot IS NULL
    OR item.utility_cost_snapshot IS NULL
    OR item.total_cost_snapshot IS NULL
    OR item.cost_status_snapshot IS NULL
    OR item.cost_snapshot_recorded_at IS NULL
  );

